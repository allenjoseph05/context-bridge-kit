#!/bin/sh
# Install the Context Bridge native messaging host for Chrome (macOS, Linux), user level.
#
#   scripts/install-host.sh <extension-id> [--dry-run]
#
# Writes, in this order:
#   <vault>/host/context-bridge-host     launcher with node's absolute path (Chrome does not use
#                                        the shell's PATH); <vault> = $CB_VAULT or ~/.context-bridge
#   <Chrome>/NativeMessagingHosts/com.contextbridge.host.json   host manifest pointing at it
#   <vault>/config.json                  extensionId (other fields kept)
# --dry-run prints the manifest JSON on stdout (details on stderr) and writes nothing.
# Windows: use scripts/install-host.ps1.
set -eu

usage() {
  echo "usage: $0 <extension-id (32 letters a-p)> [--dry-run]" >&2
  exit 2
}

EXT_ID=""
DRY_RUN=0
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=1 ;;
    -*) usage ;;
    *) [ -z "$EXT_ID" ] || usage; EXT_ID="$arg" ;;
  esac
done
printf '%s' "$EXT_ID" | grep -Eq '^[a-p]{32}$' || usage

NODE=$(command -v node || true)
if [ -z "$NODE" ]; then
  echo "node not found on PATH; install Node 20+ first" >&2
  exit 1
fi
# Absolute, symlinks resolved, so the launcher keeps working outside this shell.
NODE=$("$NODE" -e 'process.stdout.write(require("fs").realpathSync(process.execPath))')

REPO=$(cd "$(dirname "$0")/.." && pwd -P)
MAIN="$REPO/packages/host/dist/main.js"
VAULT="${CB_VAULT:-$HOME/.context-bridge}"
HOST_DIR="$VAULT/host"
LAUNCHER="$HOST_DIR/context-bridge-host"
NAME="com.contextbridge.host"

case "$(uname -s)" in
  Darwin) CHROME_DIR="$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts" ;;
  Linux) CHROME_DIR="$HOME/.config/google-chrome/NativeMessagingHosts" ;;
  *)
    if [ "$DRY_RUN" -eq 0 ]; then
      echo "unsupported OS $(uname -s); on Windows run scripts/install-host.ps1" >&2
      exit 1
    fi
    CHROME_DIR="(unsupported OS $(uname -s); on Windows run scripts/install-host.ps1)"
    ;;
esac
MANIFEST_PATH="$CHROME_DIR/$NAME.json"

# JSON built by node so paths are escaped correctly.
MANIFEST=$("$NODE" -e '
  const [path, id] = process.argv.slice(1);
  process.stdout.write(JSON.stringify({
    name: "com.contextbridge.host",
    description: "Context Bridge local host",
    path,
    type: "stdio",
    allowed_origins: [`chrome-extension://${id}/`],
  }, null, 2) + "\n");
' "$LAUNCHER" "$EXT_ID")

# Single-quote a string for sh.
sq() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }
LAUNCHER_TEXT="#!/bin/sh
# Generated by scripts/install-host.sh. Chrome starts the host through this file.
exec $(sq "$NODE") $(sq "$MAIN") \"\$@\"
"

if [ "$DRY_RUN" -eq 1 ]; then
  printf '%s\n' "$MANIFEST"
  {
    echo "# dry run: nothing written"
    echo "# manifest -> $MANIFEST_PATH"
    echo "# launcher -> $LAUNCHER:"
    printf '%s' "$LAUNCHER_TEXT" | sed 's/^/#   /'
    echo "# config   -> $VAULT/config.json (extensionId = $EXT_ID)"
  } >&2
  exit 0
fi

[ -f "$MAIN" ] || echo "warning: $MAIN not found; run 'pnpm build' before using the host" >&2

umask 077
mkdir -p "$HOST_DIR"
chmod 700 "$VAULT" "$HOST_DIR"
printf '%s' "$LAUNCHER_TEXT" > "$LAUNCHER"
chmod 700 "$LAUNCHER"

mkdir -p "$CHROME_DIR"
printf '%s\n' "$MANIFEST" > "$MANIFEST_PATH"
chmod 600 "$MANIFEST_PATH"

"$NODE" -e '
  const fs = require("fs");
  const [file, id] = process.argv.slice(1);
  let config = { defaults: { expiryDays: 7 } };
  try { config = JSON.parse(fs.readFileSync(file, "utf8")); } catch (e) { if (e.code !== "ENOENT") throw e; }
  config.extensionId = id;
  const tmp = file + ".tmp";
  fs.writeFileSync(tmp, JSON.stringify(config, null, 2) + "\n", { mode: 0o600 });
  fs.renameSync(tmp, file);
' "$VAULT/config.json" "$EXT_ID"

echo "installed $NAME for chrome-extension://$EXT_ID/" >&2
echo "  manifest: $MANIFEST_PATH" >&2
echo "  launcher: $LAUNCHER" >&2
