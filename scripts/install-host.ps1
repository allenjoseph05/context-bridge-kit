# Install the Context Bridge native messaging host for Chrome on Windows, user level.
#
#   powershell -ExecutionPolicy Bypass -File scripts\install-host.ps1 <extension-id> [--dry-run | -DryRun]
#
# Writes, in this order:
#   <vault>\host\context-bridge-host.cmd       launcher with node's absolute path (Chrome does not
#                                              use the shell's PATH); <vault> = $env:CB_VAULT or
#                                              ~\.context-bridge
#   <vault>\host\com.contextbridge.host.json   host manifest pointing at the launcher
#   HKCU\Software\Google\Chrome\NativeMessagingHosts\com.contextbridge.host  (default) = manifest path
#   <vault>\config.json                        extensionId (other fields kept)
# --dry-run prints the manifest JSON on stdout (details on stderr) and writes nothing.
param(
  [Parameter(Mandatory = $true, Position = 0)][string]$ExtensionId,
  [switch]$DryRun,
  [Parameter(ValueFromRemainingArguments = $true)][string[]]$Rest
)
$ErrorActionPreference = 'Stop'

foreach ($a in $Rest) {
  if ($a -eq '--dry-run') { $DryRun = $true } else { throw "unknown argument: $a" }
}
if ($ExtensionId -cnotmatch '^[a-p]{32}$') {
  throw "usage: install-host.ps1 <extension-id (32 letters a-p)> [--dry-run]"
}

$nodeCmd = Get-Command node -ErrorAction SilentlyContinue
if ($null -eq $nodeCmd) { throw 'node not found on PATH; install Node 20+ first' }
$node = (Resolve-Path $nodeCmd.Source).Path

$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$main = Join-Path $repo 'packages\host\dist\main.js'
if ($env:CB_VAULT) { $vault = $env:CB_VAULT } else { $vault = Join-Path $HOME '.context-bridge' }
$hostDir = Join-Path $vault 'host'
$launcher = Join-Path $hostDir 'context-bridge-host.cmd'
$name = 'com.contextbridge.host'
$manifestPath = Join-Path $hostDir "$name.json"
$regKey = "HKCU:\Software\Google\Chrome\NativeMessagingHosts\$name"

# JSON built by node so paths are escaped correctly (and written without a BOM). The inline
# scripts use single quotes only: PowerShell 5.1 does not escape double quotes for native programs.
$manifestScript = @'
const [path, id] = process.argv.slice(1);
process.stdout.write(JSON.stringify({
  name: 'com.contextbridge.host',
  description: 'Context Bridge local host',
  path,
  type: 'stdio',
  allowed_origins: ['chrome-extension://' + id + '/'],
}, null, 2) + '\n');
'@
$manifest = (& $node -e $manifestScript $launcher $ExtensionId) -join "`n"
if ($LASTEXITCODE -ne 0) { throw 'could not build the manifest' }

$launcherText = "@echo off`r`nrem Generated by scripts\install-host.ps1. Chrome starts the host through this file.`r`n`"$node`" `"$main`" %*`r`n"

if ($DryRun) {
  [Console]::Out.Write($manifest + "`n")
  [Console]::Error.WriteLine('# dry run: nothing written')
  [Console]::Error.WriteLine("# manifest -> $manifestPath")
  [Console]::Error.WriteLine("# registry -> $regKey (default) = $manifestPath")
  [Console]::Error.WriteLine("# launcher -> ${launcher}:")
  foreach ($line in ($launcherText -split "`r`n")) { if ($line) { [Console]::Error.WriteLine("#   $line") } }
  [Console]::Error.WriteLine("# config   -> $(Join-Path $vault 'config.json') (extensionId = $ExtensionId)")
  exit 0
}

if (-not (Test-Path $main)) { Write-Warning "$main not found; run 'pnpm build' before using the host" }

$utf8 = New-Object System.Text.UTF8Encoding $false
New-Item -ItemType Directory -Force -Path $hostDir | Out-Null
[System.IO.File]::WriteAllText($launcher, $launcherText, $utf8)
[System.IO.File]::WriteAllText($manifestPath, $manifest + "`n", $utf8)

New-Item -Path $regKey -Force | Out-Null
Set-ItemProperty -Path $regKey -Name '(default)' -Value $manifestPath

$configScript = @'
const fs = require('fs');
const [file, id] = process.argv.slice(1);
let config = { defaults: { expiryDays: 7 } };
try { config = JSON.parse(fs.readFileSync(file, 'utf8')); } catch (e) { if (e.code !== 'ENOENT') throw e; }
config.extensionId = id;
const tmp = file + '.tmp';
fs.writeFileSync(tmp, JSON.stringify(config, null, 2) + '\n', { mode: 0o600 });
fs.renameSync(tmp, file);
'@
& $node -e $configScript (Join-Path $vault 'config.json') $ExtensionId
if ($LASTEXITCODE -ne 0) { throw 'could not write the vault config' }

[Console]::Error.WriteLine("installed $name for chrome-extension://$ExtensionId/")
[Console]::Error.WriteLine("  manifest: $manifestPath")
[Console]::Error.WriteLine("  registry: $regKey")
[Console]::Error.WriteLine("  launcher: $launcher")
